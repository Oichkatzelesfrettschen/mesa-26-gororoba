#define SAFE_COUNT (sizeof(safe_registers) / sizeof(safe_registers[0]))
#define CHECKED_COUNT \
   (sizeof(checked_registers) / sizeof(checked_registers[0]))

/* The counts the derivation in the header produced.  A row added or
 * dropped without re-running it against the named kernel source moves
 * these, which the self-check reports. */
#define SAFE_COUNT_DERIVED 685u
#define CHECKED_COUNT_DERIVED 142u

const struct r300_kernel_register *
r300_kernel_safe_registers(uint32_t *count_out)
{
   if (count_out != NULL)
      *count_out = (uint32_t)SAFE_COUNT;
   return safe_registers;
}

const struct r300_kernel_register *
r300_kernel_checked_registers(uint32_t *count_out)
{
   if (count_out != NULL)
      *count_out = (uint32_t)CHECKED_COUNT;
   return checked_registers;
}

static bool
member(const struct r300_kernel_register *table, size_t count, uint32_t reg)
{
   /* Both tables are ascending, which the self-check holds. */
   size_t low = 0;
   size_t high = count;
   while (low < high) {
      const size_t mid = low + (high - low) / 2;
      if (table[mid].offset == reg)
         return true;
      if (table[mid].offset < reg)
         low = mid + 1;
      else
         high = mid;
   }
   return false;
}

bool
r300_kernel_register_safe_listed(uint32_t reg)
{
   return member(safe_registers, SAFE_COUNT, reg);
}

bool
r300_kernel_register_checked(uint32_t reg)
{
   return member(checked_registers, CHECKED_COUNT, reg);
}

bool
r300_kernel_admits_packet0_register(uint32_t reg)
{
   if (reg >= R300_KERNEL_PACKET0_REGISTER_LIMIT)
      return false;
   return r300_kernel_register_safe_listed(reg) ||
          r300_kernel_register_checked(reg);
}

static int
check_table(const struct r300_kernel_register *table, size_t count)
{
   for (size_t i = 0; i < count; i++) {
      if (i > 0 && table[i].offset <= table[i - 1].offset)
         return -EINVAL;
      /* A PACKET0 header addresses registers in dword units. */
      if ((table[i].offset & 3u) != 0u)
         return -EINVAL;
   }
   return 0;
}

int
r300_kernel_packet0_authority_self_check(void)
{
   if (SAFE_COUNT != SAFE_COUNT_DERIVED ||
       CHECKED_COUNT != CHECKED_COUNT_DERIVED)
      return -EINVAL;
   if (R300_KERNEL_PACKET0_REGISTER_LIMIT !=
       R300_KERNEL_PACKET0_BITMAP_WORDS * 32u * 4u)
      return -EINVAL;
   if (check_table(safe_registers, SAFE_COUNT) != 0 ||
       check_table(checked_registers, CHECKED_COUNT) != 0)
      return -EINVAL;

   /* A cleared bitmap bit skips the check, so a safe-listed register
    * never reaches a case label.  The two tables are disjoint. */
   for (size_t i = 0; i < SAFE_COUNT; i++) {
      if (r300_kernel_register_checked(safe_registers[i].offset))
         return -EINVAL;
      if (safe_registers[i].name == NULL)
         return -EINVAL;
      /* reg_srcs/r300 lists nothing the bitmap cannot reach. */
      if (safe_registers[i].offset >= R300_KERNEL_PACKET0_REGISTER_LIMIT)
         return -EINVAL;
   }
   for (size_t i = 0; i < CHECKED_COUNT; i++) {
      if (r300_kernel_register_safe_listed(checked_registers[i].offset))
         return -EINVAL;
   }
   return 0;
}
